# ---- End of Day ---------------------------------------------------------------

def test_eod_review_counts_only_the_managers_branch(admin_client, manager_a, branch, branch_b, table_a, table_b, menu_item, paneer_b):
    _, admin = admin_client
    _, manager = manager_a
    bill_a = _paid_bill(table_a, menu_item, 1)
    bill_b = _paid_bill(table_b, menu_item, 2)
    inventory_services.record_wastage(paneer_b.id, Decimal("1.00"), "SPOILED")

    mine = manager.get("/v1/admin/eod-review/").data
    assert mine["branch"] == str(branch.id)
    assert mine["tables_served"] == 1
    assert Decimal(str(mine["total_collected"])) == bill_a.total_amount
    assert mine["wastage_entries_count"] == 0  # the spoiled Paneer is Second Branch's

    everything = admin.get("/v1/admin/eod-review/").data
    assert everything["branch"] is None
    assert everything["tables_served"] == 2
    assert everything["wastage_entries_count"] == 1

    theirs = admin.get(f"/v1/admin/eod-review/?branch={branch_b.id}").data
    assert Decimal(str(theirs["total_collected"])) == bill_b.total_amount

    assert manager.get(f"/v1/admin/eod-review/?branch={branch_b.id}").status_code == 403


def test_ai_eod_report_hands_the_model_only_the_managers_branch(
    manager_a, branch, table_a, table_b, menu_item, chicken_a, paneer_b, monkeypatch,
):
    _, manager = manager_a
    _paid_bill(table_a, menu_item, 1)
    _paid_bill(table_b, menu_item, 2)
    captured = {}

    def fake_generate_json(system_prompt, user_prompt, **kwargs):
        captured["facts"] = json.loads(user_prompt)
        return {"summary": "ok", "recommendations": []}

    monkeypatch.setattr("core.ai_client.generate_json", fake_generate_json)

