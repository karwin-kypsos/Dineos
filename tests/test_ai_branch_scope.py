    stranded = AIInsight.objects.create(restaurant=restaurant, ingredient=chicken_a, severity="ALERT", headline="x")
    unbranched = AIInsight.objects.create(restaurant=restaurant, ingredient=legacy, severity="ALERT", headline="y")

    migration = importlib.import_module("apps.inventory.migrations.0008_backfill_ai_insight_branch")
