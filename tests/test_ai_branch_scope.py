def _paid_bill(table, menu_item, quantity):
    from apps.billing import services as billing_services
    from apps.orders import services as order_services
    from apps.tables import services as table_services

    session, _ = table_services.get_or_create_active_session(table.id)
    order_services.place_order(session.id, [{"menu_item_id": menu_item.id, "quantity": quantity}])
    return billing_services.pay_bill(session.id, "CASH", None)


def _order_on(table, menu_item, quantity, when):
    # Same shape as tests/test_prep_forecast.py: a historical, already
    # closed visit so several can sit on one table.
    session = TableSession.objects.create(table=table, status=TableSession.Status.CLOSED)
    order = Order.objects.create(table=table, session=session, order_type="DINE_IN", status="SERVED")
    Order.objects.filter(id=order.id).update(placed_at=when)
    OrderItem.objects.create(order=order, menu_item=menu_item, quantity=quantity, unit_price=menu_item.price)


def _snapshot(messages):
    return json.loads(messages[0]["content"].split("snapshot: ", 1)[1])


# ---- AI Insights ------------------------------------------------------------

def test_admin_generated_insights_carry_their_ingredients_branch(
    admin_client, manager_a, branch, branch_b, chicken_a, paneer_b, monkeypatch,
):
    _, admin = admin_client
    _, manager = manager_a

    def fake_generate_json(system_prompt, user_prompt, **kwargs):
        return {"insights": [
            {"ingredient_id": f["ingredient_id"], "severity": "CRITICAL",
             "headline": f"{f['ingredient_name']} is below minimum", "recommended_action": "Reorder"}
            for f in json.loads(user_prompt)["ingredients"]
        ]}

    monkeypatch.setattr("core.ai_client.generate_json", fake_generate_json)

    response = admin.post("/v1/inventory/ai-insights/generate/")

    assert response.status_code == 201, response.data
    assert AIInsight.objects.get(ingredient=chicken_a).branch_id == branch.id
    assert AIInsight.objects.get(ingredient=paneer_b).branch_id == branch_b.id

    dashboard = admin.get(f"/v1/admin/dashboard/?branch={branch.id}").data
    assert dashboard["ai_daily_insight"]["headline"] == "Chicken is below minimum"

    feed = manager.get("/v1/inventory/ai-insights/").data
    rows = feed["results"] if "results" in feed else feed
    assert [r["ingredient_name"] for r in rows] == ["Chicken"]


def test_backfill_gives_branchless_insights_their_ingredients_branch(restaurant, branch, chicken_a):
    from django.apps import apps as django_apps

